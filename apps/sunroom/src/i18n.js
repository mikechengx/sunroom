export function setLanguage(next){
 if(!['zh','en'].includes(next))return false;
 language=next;try{localStorage.setItem('sunroom.lang',language);const url=new URL(location.href);url.searchParams.set('lang',language);history.replaceState(null,'',url);}catch{}
 updateSwitch();translateDOM();window.dispatchEvent(new CustomEvent('sunroom:languagechange',{detail:{language}}));return true;
}
